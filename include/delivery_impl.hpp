#pragma once

#include <cstddef>
#include <cstdint>

#include "crc.hpp"
#include "delivery.hpp"
#include "packet.hpp"
#include "project_config.hpp"

namespace connectivity
{
  namespace delivery
  {

	template<typename Config>
	  void Delivery<Config>::init()
	  {
		m_buffer = { };
		m_size = 0U;
	  }

	template<typename Config>
	  DeliveryError Delivery<Config>::prepareHandshake(PacketType type)
	  {
		/*
		 * ACK and NAK are the only valid handshake types.
		 */
		if((type != PacketType::Ack) && (type != PacketType::Nak))
		{
		  m_size = 0U;
		  return DeliveryError::InvalidType;
		}

		constexpr std::size_t kFrameSize = 9U;

		if(kFrameSize > Config::kTxBufferSize)
		{
		  m_size = 0U;
		  return DeliveryError::BufferOverflow;
		}

		std::size_t index = 0U;
		std::uint16_t crc = kCrcInitialValue;

		/*
		 * SYNC and SOF are not included in CRC.
		 */
		m_buffer[index++] = kSyncByte;
		m_buffer[index++] = kSofByte;

		const std::uint8_t typeByte = static_cast<std::uint8_t>(type);

		m_buffer[index++] = typeByte;

		crc = crc::crc16::update(typeByte, crc);

		/*
		 * Handshake packets do not contain payload.
		 */
		const std::uint8_t lengthLsb = 0U;
		const std::uint8_t lengthMsb = 0U;

		m_buffer[index++] = lengthLsb;

		crc = crc::crc16::update(lengthLsb, crc);

		m_buffer[index++] = lengthMsb;

		crc = crc::crc16::update(lengthMsb, crc);

		const std::uint8_t mainCommand = 0U;
		const std::uint8_t subCommand = 0U;

		m_buffer[index++] = mainCommand;

		crc = crc::crc16::update(mainCommand, crc);

		m_buffer[index++] = subCommand;

		crc = crc::crc16::update(subCommand, crc);

		/*
		 * CRC is transmitted LSB first.
		 */
		m_buffer[index++] = static_cast<std::uint8_t>(crc & 0x00FFU);

		m_buffer[index++] = static_cast<std::uint8_t>((crc >> 8U) & 0x00FFU);

		m_size = index;

		return DeliveryError::Success;
	  }

	template<typename Config>
	  DeliveryError Delivery<Config>::prepareData(PacketType type,
												  std::uint8_t mainCommand,
												  std::uint8_t subCommand,
												  const std::uint8_t *data,
												  std::uint16_t length)
	  {
		/*
		 * Data packets are currently not generated by this API.
		 * Only application data packet types are allowed here.
		 */
		if((type != PacketType::Request) && (type != PacketType::Response)
			&& (type != PacketType::Event))
		{
		  m_size = 0U;
		  return DeliveryError::InvalidType;
		}

		/*
		 * NULL is valid only for zero-length payload.
		 */
		if((length > 0U) && (data == nullptr))
		{
		  m_size = 0U;
		  return DeliveryError::InvalidData;
		}

		if(length > Config::kMaxPayloadSize)
		{
		  m_size = 0U;
		  return DeliveryError::InvalidLength;
		}

		constexpr std::size_t kHeaderSize = 7U;
		constexpr std::size_t kCrcSize = 2U;

		const std::size_t frameSize = kHeaderSize
			+ static_cast<std::size_t>(length) + kCrcSize;

		if(frameSize > Config::kTxBufferSize)
		{
		  m_size = 0U;
		  return DeliveryError::BufferOverflow;
		}

		std::size_t index = 0U;
		std::uint16_t crc = kCrcInitialValue;

		/*
		 * SYNC and SOF are not included in CRC.
		 */
		m_buffer[index++] = kSyncByte;
		m_buffer[index++] = kSofByte;

		const std::uint8_t typeByte = static_cast<std::uint8_t>(type);

		m_buffer[index++] = typeByte;

		crc = crc::crc16::update(typeByte, crc);

		const std::uint8_t lengthLsb = static_cast<std::uint8_t>(length
			& 0x00FFU);

		const std::uint8_t lengthMsb = static_cast<std::uint8_t>((length >> 8U)
			& 0x00FFU);

		m_buffer[index++] = lengthLsb;

		crc = crc::crc16::update(lengthLsb, crc);

		m_buffer[index++] = lengthMsb;

		crc = crc::crc16::update(lengthMsb, crc);

		m_buffer[index++] = mainCommand;

		crc = crc::crc16::update(mainCommand, crc);

		m_buffer[index++] = subCommand;

		crc = crc::crc16::update(subCommand, crc);

		for (std::size_t i = 0U; i < length; ++i)
		{
		  m_buffer[index++] = data[i];

		  crc = crc::crc16::update(data[i], crc);
		}

		/*
		 * CRC is transmitted LSB first.
		 */
		m_buffer[index++] = static_cast<std::uint8_t>(crc & 0x00FFU);

		m_buffer[index++] = static_cast<std::uint8_t>((crc >> 8U) & 0x00FFU);

		m_size = index;

		return DeliveryError::Success;
	  }

  } // namespace packet
} // namespace connectivity
